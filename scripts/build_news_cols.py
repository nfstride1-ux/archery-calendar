#!/usr/bin/env python3
"""Rebuild the NEWS_COLS block in app.js from the real newsletter pages (newsletter/<slug>/index.html).
The two tall desktop columns on the home pages show the article text exactly as written there (no rewriting).
Run after editing an article:  python3 scripts/build_news_cols.py"""
import re, json, html, sys, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ISSUES = [('yankton-world-championships-2026', 'Yankton world championships'), ('hobart-nationals-2026', 'Hobart nationals')]
out = []
for slug, short in ISSUES:
    s = open(f'{root}/newsletter/{slug}/index.html', encoding='utf-8').read()
    title = html.unescape(re.search(r'<h1>(.*?)</h1>', s, re.S).group(1))
    date = html.unescape(re.search(r'</h1><p>(.*?)</p></div></section>', s, re.S).group(1))
    body = re.search(r'<article class="panel nl-body">(.*?)</article>', s, re.S).group(1)
    blocks = []
    for m in re.finditer(r'<(p|h2|ul|figure|aside)\b([^>]*)>(.*?)</\1>', body, re.S):
        tag, attrs, inner = m.groups()
        if tag in ('figure', 'aside') or 'nl-greet' in attrs: continue
        if tag == 'p' and 'class="btn' in inner: continue
        if tag == 'h2': blocks.append(['h', inner.strip()])
        elif tag == 'ul': blocks += [['li', li.strip()] for li in re.findall(r'<li>(.*?)</li>', inner, re.S)]
        else: blocks.append(['n' if 'nl-note' in attrs else 'p', inner.strip()])
    out.append({'url': f'newsletter/{slug}/', 'short': short, 'title': title, 'date': date, 'blocks': blocks})
js = 'const NEWS_COLS = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';'
p = f'{root}/app.js'; a = open(p, encoding='utf-8').read()
new = '/*NEWS_COLS:BEGIN (generated by scripts/build_news_cols.py from the newsletter pages; do not edit by hand)*/\n' + js + '\n/*NEWS_COLS:END*/'
if '/*NEWS_COLS:BEGIN' in a: a = re.sub(r'/\*NEWS_COLS:BEGIN.*?/\*NEWS_COLS:END\*/', lambda m: new, a, flags=re.S)
else:
    k = a.index('const newsItems = code =>'); a = a[:k] + new + '\n' + a[k:]
open(p, 'w', encoding='utf-8').write(a)
print('ok', [(o['short'], len(o['blocks'])) for o in out])
