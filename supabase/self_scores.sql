-- Archery Calendar: "Add my score" – self-reported (unofficial) scores on every shoot (16 Oct 2026). Safe to re-run.
-- Needs the earlier files (profiles, is_admin(), bot_tokens from admin_requests.sql). Run the whole file once in the Supabase SQL editor.

-- 1. When each shoot is open for scores: start date 00:00 local -> end of the day after the last day (local time).
create table if not exists public.score_windows (
  event_id text primary key, opens_at timestamptz not null, closes_at timestamptz not null, tz text,
  check (closes_at > opens_at));
alter table public.score_windows enable row level security;
drop policy if exists "windows: read" on public.score_windows;
create policy "windows: read" on public.score_windows for select to anon, authenticated using (true);
grant select on public.score_windows to anon, authenticated;

-- Open right now? Listed shoots use score_windows; club-submitted shoots ("sub-<uuid>") use their own dates, Perth time.
create or replace function public.score_open(p_event text) returns boolean language sql stable security definer set search_path = public as $$
  select coalesce(
    (select now() >= w.opens_at and now() < w.closes_at from score_windows w where w.event_id = p_event),
    (select now() >= (s.start_date::timestamp at time zone 'Australia/Perth')
        and now() < ((coalesce(s.end_date, s.start_date) + 2)::timestamp at time zone 'Australia/Perth')
       from submitted_events s where p_event = 'sub-' || s.id::text and s.status = 'live'),
    false);
$$;
grant execute on function public.score_open(text) to anon, authenticated;

-- 2. The scores. One per archer per shoot per round/division.
create table if not exists public.self_scores (
  id uuid primary key default gen_random_uuid(),
  event_id text not null check (length(event_id) between 1 and 200),
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  display_name text not null check (length(display_name) between 1 and 60),
  division text not null check (length(division) between 1 and 80),
  bow text not null check (bow in ('Recurve','Compound','Barebow','Longbow','Traditional','Crossbow','Other')),
  score int not null check (score between 0 and 3000),
  tens int check (tens between 0 and 300), xs int check (xs between 0 and 300),
  place int check (place between 1 and 999),
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  check (xs is null or tens is null or xs <= tens),
  unique (event_id, user_id, division));
create index if not exists self_scores_event on public.self_scores (event_id);
alter table public.self_scores enable row level security;

-- Name comes from the profile (never the email); emails, phone numbers and web addresses are refused.
create or replace function public.self_scores_guard() returns trigger language plpgsql security definer set search_path = public as $$
declare nm text;
begin
  if not public.is_admin() or tg_op = 'INSERT' then
    if auth.uid() is null then raise exception 'sign in to add a score'; end if;
    new.user_id := auth.uid();
    if not public.score_open(new.event_id) then raise exception 'scores for this shoot are closed'; end if;
  end if;
  if tg_op = 'UPDATE' then new.created_at := old.created_at; new.event_id := old.event_id; new.user_id := old.user_id; end if;
  if tg_op = 'INSERT' then new.created_at := now(); end if;
  new.updated_at := now();
  select nullif(trim(display_name), '') into nm from profiles where id = new.user_id;
  new.display_name := left(trim(coalesce(nm, new.display_name, '')), 60);
  new.division := left(trim(new.division), 80);
  if new.display_name = '' then raise exception 'add a display name on your account first'; end if;
  if new.display_name ~ '@|\d{6,}|https?:' or new.division ~ '@|\d{6,}|https?:' then raise exception 'no emails, phone numbers or links please'; end if;
  return new;
end $$;
drop trigger if exists self_scores_guard on public.self_scores;
create trigger self_scores_guard before insert or update on public.self_scores for each row execute function public.self_scores_guard();

drop policy if exists "self: read" on public.self_scores;
create policy "self: read" on public.self_scores for select to anon, authenticated using (true);
drop policy if exists "self: insert own" on public.self_scores;
create policy "self: insert own" on public.self_scores for insert to authenticated with check (user_id = auth.uid() and public.score_open(event_id));
drop policy if exists "self: update own" on public.self_scores;
create policy "self: update own" on public.self_scores for update to authenticated using (user_id = auth.uid() and public.score_open(event_id)) with check (user_id = auth.uid() and public.score_open(event_id));
drop policy if exists "self: delete own or admin" on public.self_scores;
create policy "self: delete own or admin" on public.self_scores for delete to authenticated using ((user_id = auth.uid() and public.score_open(event_id)) or public.is_admin());
-- the browser never sees user_id (no emails either – they are not in this table)
revoke all on public.self_scores from anon, authenticated;
grant select (id, event_id, display_name, division, bow, score, tens, xs, place, created_at, updated_at) on public.self_scores to anon, authenticated;
grant insert (event_id, display_name, division, bow, score, tens, xs, place), update (display_name, division, bow, score, tens, xs, place), delete on public.self_scores to authenticated;

-- Which of these rows are mine? (so the page can show Edit on your own entries without exposing user ids)
create or replace function public.my_self_scores(p_event text) returns setof uuid language sql stable security definer set search_path = public as $$
  select id from self_scores where event_id = p_event and user_id = auth.uid();
$$;
grant execute on function public.my_self_scores(text) to authenticated;

-- 3. Bot keeps the windows up to date as shoots are added (scripts/score_windows.py push). Token-gated, windows only.
create or replace function public.bot_set_score_windows(p_token text, p_rows jsonb) returns jsonb language plpgsql security definer set search_path = public, extensions as $$
declare n int;
begin
  if p_token is null or not exists (select 1 from bot_tokens where token_hash = encode(digest(p_token, 'sha256'), 'hex')) then raise exception 'bad token'; end if;
  insert into score_windows (event_id, opens_at, closes_at, tz)
    select r->>'event_id', (r->>'opens_at')::timestamptz, (r->>'closes_at')::timestamptz, r->>'tz' from jsonb_array_elements(p_rows) r
  on conflict (event_id) do update set opens_at = excluded.opens_at, closes_at = excluded.closes_at, tz = excluded.tz;
  get diagnostics n = row_count; return jsonb_build_object('ok', true, 'windows', n);
end $$;
revoke all on function public.bot_set_score_windows(text, jsonb) from public;
grant execute on function public.bot_set_score_windows(text, jsonb) to anon, authenticated;

